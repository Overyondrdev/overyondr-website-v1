// Bundles public/ into src/static.generated.js so the Worker serves its own files (no separate asset upload).
// Wrangler runs this automatically before `wrangler dev` and `wrangler deploy` (build.command in wrangler.jsonc).
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
import { createHash } from 'node:crypto';

const root = new URL('../public/', import.meta.url).pathname;
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.woff2': 'font/woff2', '.csv': 'text/csv; charset=utf-8', '.txt': 'text/plain; charset=utf-8',
};
const walk = (dir) => readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)]));
const files = {};
for (const file of walk(root).sort()) {
  const type = TYPES[extname(file)];
  if (!type) continue;
  const buf = readFileSync(file);
  files['/' + relative(root, file)] = { type, etag: createHash('sha1').update(buf).digest('hex').slice(0, 16), b64: buf.toString('base64') };
}
writeFileSync(new URL('../src/static.generated.js', import.meta.url),
  '// Generated by scripts/bundle.mjs from public/. Do not edit.\nexport default ' + JSON.stringify(files) + ';\n');
console.log(`bundled ${Object.keys(files).length} files from public/`);
